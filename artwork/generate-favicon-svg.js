// Generate favicon.svg AND favicon.ico from the same hex-piece definition,
// rendered in the game's "pillow" tier style (rounded corners + radial
// sheen + thin bottom-edge stroke). Mirrors public/shared/CanvasUtils.js's
// _stampHexPillow so the favicon matches the in-game Lv 6–10 cells.
//
// Three outputs, same mark, different framing:
// - public/shared/brand-mark.svg: the bare triad on transparency, composited
//   onto app surfaces by the .brand-lockup markup — must stay unframed.
// - favicon.svg / favicon.ico: the triad in an app-icon frame (rounded square
//   on flat plum), so it reads on light AND dark browser chrome the way the
//   tvOS / Android / AirConsole icons do. A bare transparent mark vanishes
//   against a dark tab strip. The .ico is the multi-size raster bundle
//   (16/32/48/64) for browsers without SVG-favicon support and tools that
//   probe /favicon.ico by convention.
// - public/apple-touch-icon.png: the same frame full-bleed and opaque, for an
//   iOS home-screen add. iOS applies its own squircle mask and composites any
//   alpha onto black, so this one must not be pre-rounded or transparent.
//
// The ICO is generated by shelling out to ImageMagick (`magick`). If
// `magick` isn't on PATH, the .ico step is skipped with a warning.
//
// Usage: node artwork/generate-favicon-svg.js

const fs = require('fs');
const path = require('path');
const { execFileSync, spawnSync } = require('child_process');
const os = require('os');
const { PARTY_PALETTE } = require('../public/shared/theme.js');

const SQRT3 = Math.sqrt(3);

// The brand-mark triad — three mutually adjacent cells (teal top-left, red
// below it, honey right-center), the same canonical piece as the title
// lockup. Also written to public/shared/brand-mark.svg so favicon and
// lockup can never drift apart. Colors track the game palette; the
// palette-consistency test asserts this cell order.
const CELLS = [
  { q: 0, r: 0, color: PARTY_PALETTE[1] }, // teal
  { q: 0, r: 1, color: PARTY_PALETTE[0] }, // red
  { q: 1, r: 0, color: PARTY_PALETTE[2] }, // honey
];

// Pillow-tier rendering constants (ported from CanvasUtils.js _stampHexPillow).
const CORNER_FRAC       = 0.15;   // cornerR / circumradius
const HL_OUTER_FRAC     = 1.1;    // gradient outer radius / circumradius
const HL_FOCAL_DX_FRAC  = -0.05;  // focal point offset (upper-left light)
const HL_FOCAL_DY_FRAC  = -0.10;
const STROKE_FRAC       = 0.04;   // stroke width / cell-size (size = r*√3)

// Optical centering. A bounding-box-centered triad reads as sitting left: the
// bright honey cell (rightmost, widest-reaching point) pulls the perceived
// weight right. The fix is to slide the mark toward its area centroid (center
// of mass), which lies left of the bbox center, so the mark moves right. Pure
// centroid centering overshoots (honey ends up jammed at the edge), so we take
// a fraction of the way there. OPTICAL_K = 0 is bbox-centered, 1 is full
// centroid. The right amount depends on the frame shape: a SQUARE/RECT frame
// shows the bounding box, so it wants a light nudge (0.35); a CIRCLE mask hides
// the box and wants full center-of-mass centering (1.0). The favicon renders in
// a square-ish browser tab, so it uses the square value. The circle value lives
// in artwork/tvos-icon.html (OPTICAL_K_ROUND, for the round Android launcher).
const OPTICAL_K         = 0.35;

// App-icon frame (favicon only — the brand mark stays bare). Flat plum, no
// gradient: it has to survive a 16px tab. The fill matches the tvOS icon's back
// layer (artwork/generate-tvos-icons.js ICON.bg) and sits between --bg-primary
// and --bg-card. ICON_MARK_FRAC is the mark's optically-framed box as a
// fraction of the icon edge — a touch more generous than the Android adaptive
// icon, which has to reserve a mask safe zone the favicon doesn't.
const ICON_BG           = '#241E38';
const ICON_SIZE         = 64;
const ICON_CORNER_FRAC  = 0.22;   // cornerR / icon edge (iOS-style rounding)
const ICON_MARK_FRAC    = 0.70;
// apple-touch-icon: one 180px asset (iPhone @3x, the largest iOS asks for).
// iOS downscales it for every smaller slot, so extra sizes earn nothing.
const TOUCH_ICON_SIZE   = 180;

// Rounded-hex SVG path. Each vertex is replaced by a tangent arc of radius
// `cornerR`, matching CanvasUtils.hexPathRounded (canvas arcTo semantics:
// the path leaves the edge at tangent length cornerR/tan(60°) from the
// vertex, NOT at cornerR — trimming by the full radius makes the arc
// bulge past the edges and reads as a little circle on every corner).
function roundedHexPath(cx, cy, r, cornerR) {
  const tangent = cornerR / Math.tan(Math.PI / 3);
  const verts = [];
  for (let i = 0; i < 6; i++) {
    const a = i * Math.PI / 3;
    verts.push([cx + r * Math.cos(a), cy + r * Math.sin(a)]);
  }
  let d = '';
  for (let i = 0; i < 6; i++) {
    const prev = verts[(i + 5) % 6];
    const curr = verts[i];
    const next = verts[(i + 1) % 6];
    const inLen  = Math.hypot(curr[0] - prev[0], curr[1] - prev[1]);
    const outLen = Math.hypot(next[0] - curr[0], next[1] - curr[1]);
    const inDx  = (curr[0] - prev[0]) / inLen;
    const inDy  = (curr[1] - prev[1]) / inLen;
    const outDx = (next[0] - curr[0]) / outLen;
    const outDy = (next[1] - curr[1]) / outLen;
    const ex = curr[0] - tangent * inDx,  ey = curr[1] - tangent * inDy;
    const xx = curr[0] + tangent * outDx, xy = curr[1] + tangent * outDy;
    d += (i === 0 ? 'M' : 'L') + `${ex.toFixed(3)},${ey.toFixed(3)}`;
    d += `A${cornerR.toFixed(3)},${cornerR.toFixed(3)} 0 0 1 ${xx.toFixed(3)},${xy.toFixed(3)}`;
  }
  return d + 'Z';
}

// The triad's drawable parts plus the optically-centered box that frames it.
// Both outputs share this; only the wrapper differs.
function markGeometry() {
  const R = 10;            // hex circumradius used for layout math
  const DRAW_R = R * 0.94; // draw slightly small so adjacent cells keep a gap
  const cornerR   = DRAW_R * CORNER_FRAC;
  const lineInset = cornerR / SQRT3;
  const strokeW   = DRAW_R * SQRT3 * STROKE_FRAC;
  const hexH = SQRT3 * R;

  // Flat-top layout: cx = 1.5 * R * q, cy = hexH * (r + q/2). Cells use the
  // full R for spacing but each hex is drawn at DRAW_R so adjacent cells have
  // a small gap between them (matches the game's blockGap).
  const centers = CELLS.map(({ q, r }) => [1.5 * R * q, hexH * (r + q / 2)]);

  const drawHexH = SQRT3 * DRAW_R;
  const allX = centers.flatMap(([cx]) => [cx - DRAW_R, cx + DRAW_R]);
  const allY = centers.flatMap(([, cy]) => [cy - drawHexH / 2, cy + drawHexH / 2]);
  const minX = Math.min(...allX);
  const minY = Math.min(...allY);
  const maxX = Math.max(...allX);
  const maxY = Math.max(...allY);

  const pad = 0.5;
  // Optically center on X: frame is symmetric about a point OPTICAL_K of the way
  // from the bbox center toward the area centroid (see OPTICAL_K note). That
  // slides the mark right; the frame grows on the honey side so nothing clips
  // and the tight side keeps its `pad` margin. Y stays bbox-centered (the triad
  // is already vertically symmetric).
  const bboxCx   = (minX + maxX) / 2;
  const centroidX = centers.reduce((s, [cx]) => s + cx, 0) / centers.length;
  const frameCx  = bboxCx - OPTICAL_K * (bboxCx - centroidX);
  const halfW    = Math.max(frameCx - minX, maxX - frameCx) + pad;
  const vbX = frameCx - halfW;
  const vbY = minY - pad;
  const vbW = halfW * 2;
  const vbH = maxY - minY + pad * 2;

  // One radial gradient per cell — focal point sits upper-left of cell center.
  const defs = centers.map(([cx, cy], i) => {
    const fx = cx + DRAW_R * HL_FOCAL_DX_FRAC;
    const fy = cy + DRAW_R * HL_FOCAL_DY_FRAC;
    const gr = DRAW_R * HL_OUTER_FRAC;
    return `    <radialGradient id="hl${i}" cx="${cx.toFixed(3)}" cy="${cy.toFixed(3)}" r="${gr.toFixed(3)}" fx="${fx.toFixed(3)}" fy="${fy.toFixed(3)}" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="white" stop-opacity="0.3"/>
      <stop offset="1" stop-color="white" stop-opacity="0"/>
    </radialGradient>`;
  }).join('\n');

  // Per cell: filled rounded hex + gradient overlay (clipped by re-using the
  // same path) + a thin dark line along the bottom edge with the lineInset
  // shortening so it doesn't touch the rounded corners.
  const cells = centers.map(([cx, cy], i) => {
    const d = roundedHexPath(cx, cy, DRAW_R, cornerR);
    const v1x = cx + DRAW_R * Math.cos(Math.PI / 3);
    const v1y = cy + DRAW_R * Math.sin(Math.PI / 3);
    const v2x = cx + DRAW_R * Math.cos(2 * Math.PI / 3);
    const v2y = cy + DRAW_R * Math.sin(2 * Math.PI / 3);
    return `  <path d="${d}" fill="${CELLS[i].color}"/>
  <path d="${d}" fill="url(#hl${i})"/>
  <line x1="${(v1x - lineInset).toFixed(3)}" y1="${v1y.toFixed(3)}" x2="${(v2x + lineInset).toFixed(3)}" y2="${v2y.toFixed(3)}" stroke="black" stroke-opacity="0.25" stroke-width="${strokeW.toFixed(3)}"/>`;
  }).join('\n');

  return { defs, cells, vbX, vbY, vbW, vbH };
}

// Bare triad on transparency — the in-app lockup mark.
function generateMarkSVG() {
  const { defs, cells, vbX, vbY, vbW, vbH } = markGeometry();
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vbX.toFixed(2)} ${vbY.toFixed(2)} ${vbW.toFixed(2)} ${vbH.toFixed(2)}">
  <defs>
${defs}
  </defs>
${cells}
</svg>
`;
}

// The same triad in a plum app-icon frame, scaled to fit and centered. The
// gradients are userSpaceOnUse in mark coordinates, which is the space the
// transformed group establishes, so they ride along with the scale.
//
// cornerFrac rounds the frame: the favicon is composited exactly as authored,
// so it rounds its own corners. The apple-touch-icon passes 0 — iOS masks it
// with its own squircle, and a pre-rounded frame shows through that mask as a
// double-rounded edge with plum slivers outside it.
function framedIconSVG(cornerFrac) {
  const { defs, cells, vbX, vbY, vbW, vbH } = markGeometry();
  const S = ICON_SIZE;
  const k = (S * ICON_MARK_FRAC) / Math.max(vbW, vbH);
  const tx = S / 2 - k * (vbX + vbW / 2);
  const ty = S / 2 - k * (vbY + vbH / 2);
  const rx = S * cornerFrac;

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${S} ${S}">
  <defs>
${defs}
  </defs>
  <rect width="${S}" height="${S}"${rx ? ` rx="${rx.toFixed(3)}"` : ''} fill="${ICON_BG}"/>
  <g transform="translate(${tx.toFixed(3)},${ty.toFixed(3)}) scale(${k.toFixed(5)})">
${cells}
  </g>
</svg>
`;
}

// Rasterize an SVG at `size` via headless Chromium. Chromium handles SVG
// radial gradients faithfully; ImageMagick's built-in SVG renderer drops
// gradient fills, which is why nothing here goes through `magick svg.svg PNG:`.
// `opaque` keeps the screenshot's own backdrop: the ICO frames drop it so the
// area outside the favicon's rounded corners stays transparent, while the
// apple-touch-icon is full-bleed and must not ship an alpha channel.
async function renderPNG(browser, svg, size, dest, opaque) {
  // Inline the SVG so setContent doesn't have to fetch it via file:// (which
  // Chromium blocks from data-URL contexts). The viewBox is already square.
  const html = `<!DOCTYPE html><html><head><style>
    html,body { margin:0; padding:0; background:transparent; }
    body { width:${size}px; height:${size}px; display:flex; align-items:center; justify-content:center; }
    svg { width:100%; height:100%; }
  </style></head><body>${svg}</body></html>`;
  const page = await browser.newPage({ viewport: { width: size, height: size } });
  await page.setContent(html);
  await page.screenshot({ path: dest, omitBackground: !opaque });
  await page.close();
}

// Bundle the favicon's raster frames into a single .ico via ImageMagick.
// Returns false (with a warning) when `magick` isn't installed — the ICO is a
// fallback for browsers without SVG-favicon support, so it's worth skipping
// rather than failing the whole run.
async function generateICO(browser, svg, icoPath) {
  // spawnSync sets `error` (ENOENT) when the binary is missing, and a
  // non-zero `status` when it ran but failed. Either case is "skip and warn".
  const magick = spawnSync('magick', ['-version'], { encoding: 'utf8' });
  if (magick.error || magick.status !== 0) {
    console.warn('magick not found on PATH — skipping favicon.ico generation.');
    console.warn('Install ImageMagick (e.g. `brew install imagemagick`) and re-run to produce favicon.ico.');
    return false;
  }

  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'favicon-'));
  try {
    const frames = [];
    for (const size of [16, 32, 48, 64]) {
      const framePath = path.join(tmp, `favicon-${size}.png`);
      await renderPNG(browser, svg, size, framePath, false);
      frames.push(framePath);
    }
    execFileSync('magick', [...frames, icoPath], { stdio: 'inherit' });
    return true;
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
}

const publicDir = path.resolve(__dirname, '..', 'public');
const svgPath = path.resolve(publicDir, 'favicon.svg');
const icoPath = path.resolve(publicDir, 'favicon.ico');
const touchPath = path.resolve(publicDir, 'apple-touch-icon.png');
const markPath = path.resolve(publicDir, 'shared', 'brand-mark.svg');

const faviconSVG = framedIconSVG(ICON_CORNER_FRAC);
fs.writeFileSync(svgPath, faviconSVG);
console.log(`Generated: ${path.relative(process.cwd(), svgPath)}`);
fs.writeFileSync(markPath, generateMarkSVG());
console.log(`Generated: ${path.relative(process.cwd(), markPath)}`);

const rel = (p) => path.relative(process.cwd(), p);

(async () => {
  let chromium;
  try {
    chromium = require('playwright').chromium;
  } catch {
    console.warn('playwright not installed — skipping the raster icons (favicon.ico, apple-touch-icon.png).');
    return;
  }
  const browser = await chromium.launch();
  try {
    await renderPNG(browser, framedIconSVG(0), TOUCH_ICON_SIZE, touchPath, true);
    console.log(`Generated: ${rel(touchPath)}`);
    if (await generateICO(browser, faviconSVG, icoPath)) console.log(`Generated: ${rel(icoPath)}`);
  } finally {
    await browser.close();
  }
})().catch((err) => { console.error(err); process.exit(1); });
